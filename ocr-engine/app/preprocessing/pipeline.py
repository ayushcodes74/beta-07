"""Main image preprocessing and enhancement pipeline."""

import logging
from pathlib import Path
from typing import Any, List, Optional, Union

import numpy as np

from app.preprocessing.config import PreprocessingConfig, DEFAULT_PREPROCESSING_CONFIG
from app.preprocessing.contrast_enhancer import ContrastEnhancer
from app.preprocessing.denoiser import Denoiser
from app.preprocessing.deskewer import Deskewer
from app.preprocessing.exceptions import (
    InvalidImageError,
    ImageProcessingError,
    PreprocessingError,
)
from app.preprocessing.image_loader import ImageLoader
from app.preprocessing.image_validator import ImageValidator
from app.preprocessing.orientation_corrector import OrientationCorrector
from app.preprocessing.quality_analyzer import QualityAnalyzer
from app.preprocessing.schemas import (
    ImageQualityMetrics,
    PreprocessingResult,
    VariantsRecord,
)
from app.ingestion.pdf_validator import PDFValidator

logger = logging.getLogger(__name__)


def preprocess_page(
    image_path: str,
    submission_id: str,
    page_number: int,
    output_dir: str,
    config: Optional[PreprocessingConfig] = None,
    known_rotation: int = 0,
) -> PreprocessingResult:
    """Preprocess a single student assignment page image for downstream OCR.

    Sequence:
    1. Validate input image readability, format (PNG/JPEG), and minimum dimensions.
    2. Load image safely into memory.
    3. Detect and correct page rotation (90/180/270 degrees).
    4. Estimate and correct small skew angles.
    5. Apply gentle edge-preserving denoising (protecting thin pen strokes and math symbols).
    6. Normalize background illumination and enhance contrast adaptively.
    7. Save enhanced image to `{output_dir}/{submission_id}/enhanced/page_XXX.png`.
    8. Generate and save optional grayscale and thresholded variants.
    9. Run diagnostic image quality analysis.
    10. Clean up incomplete outputs if an error occurs, strictly preserving the original image.

    Args:
        image_path: Path to the input image generated by Module 1.
        submission_id: Unique submission identifier.
        page_number: 1-based page index.
        output_dir: Root output directory for processed artifacts.
        config: PreprocessingConfig settings (defaults to DEFAULT_PREPROCESSING_CONFIG).
        known_rotation: Prior rotation angle in degrees from PDF metadata if known.

    Returns:
        Structured PreprocessingResult model.

    Raises:
        InvalidImageError: If the input image is corrupt, empty, or too small.
        UnsupportedImageFormatError: If format is not PNG or JPEG.
        ImageProcessingError: If an error occurs during transformation or saving.
    """
    cfg = config or DEFAULT_PREPROCESSING_CONFIG

    # 1. Sanitize submission_id to prevent path traversal
    clean_submission_id = PDFValidator.validate_submission_id(submission_id)

    # 2. Validate input image
    validator = ImageValidator(config=cfg)
    try:
        resolved_img_path, _, _ = validator.validate_file(image_path)
    except PreprocessingError as e:
        e.page_number = page_number
        raise

    # 3. Setup output directories
    base_out = Path(output_dir)
    sub_dir = (base_out / clean_submission_id).resolve()
    enhanced_dir = sub_dir / "enhanced"
    variants_dir = sub_dir / "variants"

    enhanced_dir.mkdir(parents=True, exist_ok=True)
    if cfg.generate_grayscale or cfg.generate_thresholded:
        variants_dir.mkdir(parents=True, exist_ok=True)

    filename_base = f"page_{page_number:03d}"
    enhanced_path = enhanced_dir / f"{filename_base}.png"
    gray_path = variants_dir / f"{filename_base}_gray.png"
    thresh_path = variants_dir / f"{filename_base}_threshold.png"

    created_files: List[Path] = []
    warnings: List[str] = []

    try:
        # 4. Load Image
        image = ImageLoader.load_image(resolved_img_path)

        # 5. Orientation Correction
        corrector = OrientationCorrector(config=cfg)
        image, orient_corrected, applied_rot, orient_warn = corrector.correct_orientation(
            image, known_rotation=known_rotation
        )
        if orient_warn:
            warnings.append(orient_warn)

        # 6. Deskewing
        deskewer = Deskewer(config=cfg)
        image, est_skew, corr_skew, skew_warn = deskewer.deskew(image)
        if skew_warn:
            warnings.append(skew_warn)

        # 7. Denoising (Edge-preserving to protect thin pen strokes and decimal points)
        denoiser = Denoiser(config=cfg)
        image = denoiser.denoise(image)

        # 8. Illumination normalization & Adaptive Contrast Enhancement
        contrast_enhancer = ContrastEnhancer(config=cfg)
        enhanced_image = contrast_enhancer.enhance(image)

        # 9. Save Enhanced Output Image
        ImageLoader.save_image(enhanced_image, enhanced_path)
        created_files.append(enhanced_path)

        # 10. Optional Variants
        rel_gray: Optional[str] = None
        rel_thresh: Optional[str] = None

        from app.preprocessing.thresholding import ThresholdingService

        if cfg.generate_grayscale:
            gray_img = ThresholdingService.to_grayscale(enhanced_image)
            ImageLoader.save_image(gray_img, gray_path)
            created_files.append(gray_path)
            rel_gray = _format_posix_rel_path(base_out, clean_submission_id, "variants", gray_path.name)

        if cfg.generate_thresholded:
            thresh_img = ThresholdingService.generate_threshold_variant(
                enhanced_image, method=cfg.thresholding_method
            )
            ImageLoader.save_image(thresh_img, thresh_path)
            created_files.append(thresh_path)
            rel_thresh = _format_posix_rel_path(base_out, clean_submission_id, "variants", thresh_path.name)

        # 11. Quality Diagnostics
        quality_analyzer = QualityAnalyzer(config=cfg)
        quality_metrics = quality_analyzer.analyze_quality(
            enhanced_image,
            estimated_skew=est_skew,
            corrected_skew=corr_skew,
            orientation_corrected=orient_corrected,
            extra_warnings=warnings,
        )

        rel_enhanced = _format_posix_rel_path(base_out, clean_submission_id, "enhanced", enhanced_path.name)
        rel_orig = Path(image_path).as_posix()

        return PreprocessingResult(
            submission_id=clean_submission_id,
            page_number=page_number,
            status="completed",
            original_image_path=rel_orig,
            enhanced_image_path=rel_enhanced,
            variants=VariantsRecord(grayscale=rel_gray, thresholded=rel_thresh),
            image_quality=quality_metrics,
        )

    except Exception as e:
        logger.error("Preprocessing failed on page %d for submission '%s': %s", page_number, clean_submission_id, e)
        # Clean up generated partial files for this page
        for p in created_files:
            try:
                if p.exists():
                    p.unlink()
            except OSError:
                pass

        if isinstance(e, PreprocessingError):
            raise
        raise ImageProcessingError(
            f"Failed to preprocess page {page_number}: {e}", page_number=page_number
        ) from e


def preprocess_pages(
    page_images: List[Any],
    submission_id: str,
    output_dir: str,
    config: Optional[PreprocessingConfig] = None,
) -> List[PreprocessingResult]:
    """Batch preprocess a list of page images for a submission.

    Processes pages independently so a single problematic page does not corrupt
    or cancel the processing of other valid pages in the submission.

    Args:
        page_images: List of image paths (strings), dicts, or PageRecord objects.
        submission_id: Unique submission ID.
        output_dir: Target output root directory.
        config: Optional PreprocessingConfig override.

    Returns:
        List of PreprocessingResult objects for all pages.
    """
    results: List[PreprocessingResult] = []

    for idx, item in enumerate(page_images):
        # Extract path, page_number, and optional known rotation
        known_rot = 0
        if isinstance(item, str):
            img_path = item
            page_num = idx + 1
        elif isinstance(item, dict):
            img_path = str(item.get("image_path") or item.get("path"))
            page_num = int(item.get("page_number", idx + 1))
            known_rot = int(item.get("rotation", 0))
        elif hasattr(item, "image_path"):
            img_path = str(item.image_path)
            page_num = int(getattr(item, "page_number", idx + 1))
            known_rot = int(getattr(item, "rotation", 0))
        else:
            raise InvalidImageError(f"Unsupported page item format in batch: {type(item)}")

        result = preprocess_page(
            image_path=img_path,
            submission_id=submission_id,
            page_number=page_num,
            output_dir=output_dir,
            config=config,
            known_rotation=known_rot,
        )
        results.append(result)

    return results


def _format_posix_rel_path(base_dir: Path, submission_id: str, subfolder: str, filename: str) -> str:
    """Format relative output path using forward slashes per API contract."""
    if base_dir.is_absolute():
        try:
            return (base_dir / submission_id / subfolder / filename).relative_to(Path.cwd()).as_posix()
        except ValueError:
            return f"{base_dir.name}/{submission_id}/{subfolder}/{filename}"
    return (base_dir / submission_id / subfolder / filename).as_posix()

